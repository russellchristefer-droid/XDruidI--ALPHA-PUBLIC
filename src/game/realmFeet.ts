export function realmPlateSolid(wing: -1 | 1, x: number, y: number): boolean {
  if (wing === 1) {
    if (y >= 512 || x < 2 || x > 344) return true;
    const pdx = x - 173;
    const pdy = y - 286;
    if (pdx * pdx + pdy * pdy < 36 * 36) return true;
    if (x >= 150 && x <= 184 && y >= 150 && y <= 198) return true;
    return false;
  }
  if (wing === -1 && y >= 318 && y <= 356 && x >= 124 && x <= 218) return false;
  const rows = NARAKA_SOLID;
  const row = rows[y | 0];
  if (!row) return false;
  const xi = x | 0;
  for (let i = 0; i < row.length; i += 2) {
    if (xi >= row[i]! && xi <= row[i + 1]!) return true;
  }
  return false;
}
